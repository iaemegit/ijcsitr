$ErrorActionPreference = 'Stop'
$source = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'postgresql-extracted.sql'))
$utf8 = New-Object Text.UTF8Encoding($false)
$output = New-Object Text.StringBuilder
[void]$output.AppendLine("-- Converted from ijcsitr.dump. Import into an EMPTY database only.")
[void]$output.AppendLine("SET NAMES utf8mb4; SET SESSION sql_mode='STRICT_ALL_TABLES,NO_AUTO_VALUE_ON_ZERO,NO_BACKSLASH_ESCAPES';")
$tables = [ordered]@{}
foreach ($match in [regex]::Matches($source, 'CREATE TABLE public\.(\w+) \(\r?\n([\s\S]*?)\r?\n\);')) {
    $name = $match.Groups[1].Value
    $body = $match.Groups[2].Value
    $identity = [regex]::Match($source, "ALTER TABLE public\.$name ALTER COLUMN (\w+) ADD GENERATED BY DEFAULT AS IDENTITY \([\s\S]*?SEQUENCE NAME public\.(\w+)")
    if (!$identity.Success) { throw "Missing identity: $name" }
    $pk = $identity.Groups[1].Value
    $sequence = $identity.Groups[2].Value
    $seqMatch = [regex]::Match($source, "setval\('public\.$sequence', (\d+), (true|false)\)")
    if (!$seqMatch.Success) { throw "Missing sequence value: $name" }
    $next = [long]$seqMatch.Groups[1].Value
    if ($seqMatch.Groups[2].Value -eq 'true') { $next++ }
    $columns = @()
    $definitions = @()
    foreach ($line in ($body -split '\r?\n')) {
        $colMatch = [regex]::Match($line.Trim().TrimEnd(','), '^(\w+) (.+)$')
        if (!$colMatch.Success) { throw "Unrecognized column in $name" }
        $colName = $colMatch.Groups[1].Value
        $pgType = $colMatch.Groups[2].Value
        $mysqlType = $pgType -replace 'timestamp\(6\) without time zone', 'datetime(6)' -replace 'double precision', 'double' -replace '\btext\b', 'longtext'
        $mysqlType = [regex]::Replace($mysqlType, 'character varying\((\d+)\)', { param($m) if ([int]$m.Groups[1].Value -gt 255) { 'longtext' } else { "varchar($($m.Groups[1].Value))" } })
        if ($colName -eq $pk) { $mysqlType += ' AUTO_INCREMENT PRIMARY KEY' }
        $columns += $colName
        $definitions += ('  `' + $colName + '` ' + $mysqlType)
    }
    $tables[$name] = @{ Columns = $columns; PrimaryKey = $pk; Rows = New-Object Collections.Generic.List[object]; Next = $next }
    [void]$output.AppendLine(('CREATE TABLE `' + $name + '` (' + "`n" + ($definitions -join ",`n") + "`n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;"))
}
if ($tables.Count -ne 15) { throw "Expected 15 tables, got $($tables.Count)" }
function Decode-CopyValue([string]$value) {
    [regex]::Replace($value, '\\([0-7]{1,3}|x[0-9a-fA-F]{1,2}|.)', {
        param($m)
        $token = $m.Groups[1].Value
        switch -CaseSensitive ($token) {
            'b' { return [string][char]8 }
            'f' { return [string][char]12 }
            'n' { return "`n" }
            'r' { return "`r" }
            't' { return "`t" }
            'v' { return [string][char]11 }
        }
        if ($token -match '^[0-7]{1,3}$') { return [string][char][Convert]::ToInt32($token,8) }
        if ($token -match '^x[0-9a-fA-F]+$') { return [string][char][Convert]::ToInt32($token.Substring(1),16) }
        return $token
    })
}
$active = $null
$seen = @{}
foreach ($line in ($source -split '\r?\n')) {
    if ($null -eq $active) {
        if ($line -match '^COPY public\.(\w+) \((.+)\) FROM stdin;$') {
            $active = $Matches[1]
            $copyCols = $Matches[2] -split ', '
            if (($copyCols -join ',') -ne ($tables[$active].Columns -join ',')) { throw "COPY columns mismatch: $active" }
            if ($seen.ContainsKey($active)) { throw "Repeated COPY: $active" }
            $seen[$active] = $true
        }
        continue
    }
    if ($line -eq '\.') { $active = $null; continue }
    $rawValues = $line.Split([char]9)
    if ($rawValues.Count -ne $tables[$active].Columns.Count) { throw "COPY field count mismatch: $active" }
    $values = @()
    $sqlValues = @()
    foreach ($raw in $rawValues) {
        if ($raw -ceq '\N') { $values += $null; $sqlValues += 'NULL' }
        else {
            $value = Decode-CopyValue $raw
            $values += $value
            if ($value.Length -eq 0) { $sqlValues += "''" }
            else { $sqlValues += ('CONVERT(0x' + [BitConverter]::ToString($utf8.GetBytes($value)).Replace('-','') + ' USING utf8mb4)') }
        }
    }
    $tables[$active].Rows.Add($values)
    $quotedColumns = $tables[$active].Columns | ForEach-Object { '`' + $_ + '`' }
    [void]$output.AppendLine(('INSERT INTO `' + $active + '` (' + ($quotedColumns -join ',') + ') VALUES (' + ($sqlValues -join ',') + ');'))
}
if ($active -or $seen.Count -ne $tables.Count) { throw 'Incomplete COPY data' }
$report = @()
foreach ($name in $tables.Keys) {
    $table = $tables[$name]
    $pkIndex = [array]::IndexOf($table.Columns, $table.PrimaryKey)
    $ids = @($table.Rows | ForEach-Object { $_[$pkIndex] })
    if (@($ids | Select-Object -Unique).Count -ne $ids.Count) { throw "Duplicate primary key: $name" }
    $maxId = 0L
    foreach ($id in $ids) { $maxId = [Math]::Max($maxId,[long]$id) }
    $next = [Math]::Max($table.Next, $maxId + 1)
    [void]$output.AppendLine(('ALTER TABLE `' + $name + '` AUTO_INCREMENT=' + $next + ';'))
    $report += [pscustomobject]@{ Table = $name; Rows = $table.Rows.Count; Columns = $table.Columns.Count; NextId = $next }
}
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'ijcsitr-mysql.sql'), $output.ToString(), $utf8)
$report | ConvertTo-Json | Set-Content (Join-Path $PSScriptRoot 'migration-counts.json') -Encoding UTF8
# Retain decoded rows for independent, per-value verification after import.
$expected = @{}
foreach ($name in $tables.Keys) { $expected[$name] = @{ Columns = $tables[$name].Columns; PrimaryKey = $tables[$name].PrimaryKey; Rows = @($tables[$name].Rows.ToArray()) } }
$expected | Export-Clixml (Join-Path $PSScriptRoot 'migration-expected.xml')
$report | Format-Table -AutoSize
Write-Output ('Total rows: ' + (($report | Measure-Object Rows -Sum).Sum))
